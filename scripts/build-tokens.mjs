// Turns tokens/data.mjs (exported from Figma) into:
//   styles/tokens.css            -> CSS custom properties, 3 tiers (base -> semantic -> component)
//   styles/states.generated.css  -> per-variant / per-state rules for Button and Input
//   lib/tokens.json              -> everything the docs site + Storybook display
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  baseColors, colorSteps, neutralColors, baseNumbers, baseFonts, semantics, components,
} from "../tokens/data.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const slug = (s) =>
  s.toLowerCase().replace(/sucess/g, "success").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

const tokens = []; // { tier, name, key, group, raw, alias, aliasLabel, value, kind }
const byKey = new Map();
const add = (t) => { tokens.push(t); byKey.set(t.key, t); };

// ---------- Tier 1: base ----------
for (const [family, hexes] of Object.entries(baseColors)) {
  hexes.forEach((hex, i) =>
    add({ tier: "base", group: `Color/${family}`, name: `Color/${family}/${colorSteps[i]}`,
      key: `base-color-${slug(family)}-${colorSteps[i]}`, value: hex, kind: "color" }));
}
for (const [n, hex] of Object.entries(neutralColors))
  add({ tier: "base", group: "Color/Neutral", name: `Color/Neutral/${n}`, key: `base-color-neutral-${slug(n)}`, value: hex, kind: "color" });
for (const n of baseNumbers)
  add({ tier: "base", group: "Number", name: `Number/${n}`, key: `base-number-${n}`, value: n, kind: "number" });
for (const [name, v] of Object.entries(baseFonts))
  add({ tier: "base", group: "Font", name, key: `base-${slug(name)}`, value: v, kind: "string" });

// ---------- helpers for aliases ----------
const expandAlias = (a) =>
  a.replace(/^C\//, "Color/").replace(/^N\//, "Number/").replace(/^base\/numbers\//, "Number/");
const lookup = (a) => {
  const s = slug(a);
  return byKey.get(`base-${s}`) ? `base-${s}` : byKey.get(s) ? s : null;
};
const parse = (str, tier) => {
  for (const pair of str.split("|")) {
    const i = pair.indexOf("=");
    let name = pair.slice(0, i).replace(/^c\//, "color/");
    const val = pair.slice(i + 1);
    const label = expandAlias(val.replace(/^→/, ""));
    const alias = lookup(label);
    const group = tier === "semantic" ? slug(name.split("/")[0]) + (name.startsWith("color/") ? "-" + slug(name.split("/")[1]) : "") : name.split("/")[0];
    // Semantic size/space tokens that point at a base number which does not exist in Figma (22, 240):
    let literal = null;
    if (!alias) literal = Number(label.split("/").pop());
    add({ tier, group, name, key: slug(name), alias, aliasLabel: alias ? label : null,
      literal, kind: name.startsWith("color/") || tier === "component" ? "color" : "number" });
  }
};
parse(semantics, "semantic");
parse(components, "component");

// resolve to final values
const resolve = (t) => {
  let cur = t, guard = 0;
  while (cur.alias && guard++ < 10) cur = byKey.get(cur.alias);
  return cur.value !== undefined ? cur.value : t.literal;
};
for (const t of tokens) if (t.alias || t.literal !== undefined) t.value = resolve(t);
// where the alias points to: show the immediate target's readable name
for (const t of tokens) if (t.alias) t.aliasName = byKey.get(t.alias).name;

// ---------- tokens.css ----------
const fmt = (t) => {
  if (t.tier === "base") return t.kind === "number" ? `${t.value}px` : t.kind === "string" && /^\d+$/.test(t.value) ? t.value : t.kind === "string" ? `"${t.value}"` : t.value;
  if (t.alias) return `var(--${t.alias})`;
  return `${t.literal}px`;
};
let css = "/* AUTO-GENERATED by scripts/build-tokens.mjs from tokens/data.mjs — do not edit by hand. */\n:root {\n";
for (const tier of ["base", "semantic", "component"]) {
  css += `\n  /* ===== ${tier.toUpperCase()} ===== */\n`;
  let lastGroup = "";
  for (const t of tokens.filter((x) => x.tier === tier)) {
    if (t.group !== lastGroup) { css += `  /* ${t.group} */\n`; lastGroup = t.group; }
    css += `  --${t.key}: ${fmt(t)};\n`;
  }
}
css += "}\n";
fs.writeFileSync(path.join(root, "styles/tokens.css"), css);

// ---------- states.generated.css ----------
const get = (k) => byKey.get(k);
const sel = (base, s) => ({
  default: [base],
  hover: [`${base}:hover:not(:disabled)`, `${base}[data-state="hover"]`],
  focus: [`${base}:focus-visible`, `${base}[data-state="focus"]`],
  disable: [`${base}:disabled`, `${base}[data-state="disabled"]`],
  loading: [`${base}[data-loading="true"]`, `${base}[data-state="loading"]`],
})[s];
let st = "/* AUTO-GENERATED by scripts/build-tokens.mjs — do not edit by hand. */\n";

// Button: variant x state, property = last segment of the token name
const btnProp = { bg: "--bg", text: "--fg", border: "--bd", "lead icon": "--lead", "trail icon": "--trail" };
for (const variant of ["Primary", "Primary outline", "Ghost", "Secondary", "Danger"]) {
  for (const state of ["Default", "Hover", "Focus", "Disable", "Loading"]) {
    const decls = [];
    for (const p of Object.keys(btnProp)) {
      const tk = get(slug(`Button/${variant}/${state}/${p}`));
      if (tk) decls.push(`  ${btnProp[p]}: var(--${tk.key});`);
    }
    if (!decls.length) continue;
    const selectors = sel(`.ar-btn[data-variant="${slug(variant)}"]`, state.toLowerCase()).join(",\n");
    st += `${selectors} {\n${decls.join("\n")}${state === "Focus" ? "\n  box-shadow: inset 0 0 0 1px var(--bd);" : ""}\n}\n`;
  }
}
// Input: state -> vars
const inProp = { "label text": "--label", "sublabel text": "--sub", "placeholder text": "--ph", "input text": "--text",
  bg: "--bg", border: "--bd", "leading icon": "--lead", "trailing icon": "--trail" };
const inSel = {
  Default: [`.ar-field`],
  Hover: [`.ar-field:hover:not([data-disabled="true"])`, `.ar-field[data-state="hover"]`],
  Filled: [`.ar-field[data-state="filled"]`],
  Focused: [`.ar-field:focus-within`, `.ar-field[data-state="focused"]`],
  Error: [`.ar-field[data-state="error"]`],
  Disable: [`.ar-field[data-disabled="true"]`, `.ar-field[data-state="disabled"]`],
};
for (const [state, selectors] of Object.entries(inSel)) {
  const decls = [];
  for (const p of Object.keys(inProp)) {
    const tk = get(slug(`Input/${state}/${p}`));
    if (tk) decls.push(`  ${inProp[p]}: var(--${tk.key});`);
  }
  st += `${selectors.join(",\n")} {\n${decls.join("\n")}\n}\n`;
}
fs.writeFileSync(path.join(root, "styles/states.generated.css"), st);

// ---------- tokens.json ----------
const out = tokens.map(({ tier, group, name, key, aliasName, value, kind }) =>
  ({ tier, group, name, cssVar: `--${key}`, aliasName: aliasName || null, value, kind }));
fs.writeFileSync(path.join(root, "lib/tokens.json"), JSON.stringify(out));
const c = (t) => tokens.filter((x) => x.tier === t).length;
console.log(`tokens: base ${c("base")}, semantic ${c("semantic")}, component ${c("component")} (total ${tokens.length})`);
